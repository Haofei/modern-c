fn appendCStringByte(allocator: std.mem.Allocator, out: *std.ArrayList(u8), byte: u8) !void {
    switch (byte) {
        '\\' => try out.appendSlice(allocator, "\\\\"),
        '"' => try out.appendSlice(allocator, "\\\""),
        '\'' => try out.appendSlice(allocator, "\\'"),
        '?' => try out.appendSlice(allocator, "\\?"),
        0 => try out.appendSlice(allocator, "\\000"),
        '\n' => try out.appendSlice(allocator, "\\n"),
        '\r' => try out.appendSlice(allocator, "\\r"),
        '\t' => try out.appendSlice(allocator, "\\t"),
        32...33, 35...38, 40...62, 64...91, 93...126 => try out.append(allocator, byte),
        else => {
            try out.append(allocator, '\\');
            try out.append(allocator, '0' + ((byte >> 6) & 0x07));
            try out.append(allocator, '0' + ((byte >> 3) & 0x07));
            try out.append(allocator, '0' + (byte & 0x07));
        },
    }
}

pub fn appendLayoutAsserts(
    allocator: std.mem.Allocator,
    typed_mir: *const mir.Module,
    out: *std.ArrayList(u8),
    struct_names: []const []const u8,
) anyerror!void {
    var emitter = CEmitter.init(allocator, out, typed_mir, null, null);
    defer emitter.deinit();
    try emitter.collectModule();

    try out.appendSlice(allocator,
        \\/* GENERATED by `mcc emit-layout` — DO NOT EDIT. */
        \\/* MC's authoritative struct layouts (sizeof/offsetof). A C runtime that hand-mirrors */
        \\/* one of these structs includes this header; any layout drift is a compile error.    */
        \\#include <stddef.h>
        \\
    );

    try emitter.appendLayoutAssertsFor(struct_names);
}

pub fn appendStructDecls(
    allocator: std.mem.Allocator,
    typed_mir: *const mir.Module,
    out: *std.ArrayList(u8),
    struct_names: []const []const u8,
) anyerror!void {
    var emitter = CEmitter.init(allocator, out, typed_mir, null, null);
    defer emitter.deinit();
    try emitter.collectModule();

    try out.appendSlice(allocator,
        \\/* GENERATED by `mcc emit-c-struct` — DO NOT EDIT. */
        \\/* Full C definitions of MC's authoritative shared structs (single source of truth). */
        \\/* The MC struct is the ONLY declaration; this header is regenerated from it, so a C   */
        \\/* runtime that includes it can never drift from MC's layout (there is no hand copy).  */
        \\#include <stdint.h>
        \\#include <stdbool.h>
        \\#include <stddef.h>
        \\#include <stdalign.h>
        \\
        \\
    );

    try emitter.emitNamedStructDecls(struct_names);

    // Belt-and-suspenders: also assert the generated definitions against MC's computed layout.
    try out.appendSlice(allocator, "\n/* Layout cross-check (sizeof/offsetof) against MC's authoritative layout. */\n");
    // Non-fatal: a struct with a tagged-union/nullable/overlay field whose lowered
    // layout MC does not compute at comptime is skipped (with a comment) rather than
    // aborting the whole header — the struct *definition* above is always emitted.
    try emitter.appendLayoutAssertsForImpl(struct_names, false);
}

pub fn appendModuleMir(
    allocator: std.mem.Allocator,
    typed_mir: *const mir.Module,
    out: *std.ArrayList(u8),
    source_path: ?[]const u8,
    ksan: bool,
    msan: bool,
    csan: bool,
    stub_asm: bool,
    reporter: ?*diagnostics.Reporter,
) anyerror!void {
    var emitter = CEmitter.init(allocator, out, typed_mir, source_path, reporter);
    emitter.ksan = ksan;
    emitter.msan = msan;
    emitter.csan = csan;
    emitter.stub_asm = stub_asm;
    try emitter.emitModule();
}

pub const CEmitter = struct {
    allocator: std.mem.Allocator,
    out: *std.ArrayList(u8),
    scratch: std.heap.ArenaAllocator,
    emitted_string_backings: std.AutoHashMap(mir.StringBackingId, void),
    type_aliases: std.StringHashMap(ast_bridge.TypeExpr),
    functions: std.StringHashMap(FnInfo),
    // Source function name -> overridden object/backend symbol (`#[backend_name("Y")]`).
    // Emitted as a C `__asm__("Y")` label so the object symbol is renamed without touching
    // any C-level call site.
    backend_names: std.StringHashMap([]const u8),
    structs: std.StringHashMap(ast_bridge.StructDecl),
    mmio_structs: std.StringHashMap(MmioStruct),
    packed_bits: std.StringHashMap(PackedBitsInfo),
    overlay_unions: std.StringHashMap(OverlayUnionInfo),
    tagged_unions: std.StringHashMap(ast_bridge.UnionDecl),
    enums: std.StringHashMap(ast_bridge.EnumDecl),
    array_types: std.StringHashMap(ArrayInfo),
    slice_types: std.StringHashMap(SliceInfo),
    result_types: std.StringHashMap(ResultInfo),
    // Value optionals `?T` (tagged repr), one typedef per payload type.
    opt_types: std.StringHashMap(lower_c_model.OptInfo),
    // Function-pointer signatures encountered, each emitted as a `typedef RET
    // (*name)(params);` so the name-in-the-middle C declarator works anywhere a
    // plain type name does.
    fn_ptr_types: std.StringHashMap(ast_bridge.TypeExpr),
    closure_types: std.StringHashMap(ast_bridge.TypeExpr),
    // Signature-only aggregate declarations are derived directly from the
    // module-owned SignatureTypeTable.  Unlike the legacy body registries
    // above, these records deliberately store only an ID, never TypeExpr.
    signature_type_defs: std.AutoHashMap(mir.SignatureTypeId, void),
    // `bind(scalar, f)` closures: the env is a non-pointer scalar that must be
    // widened through `uintptr_t` to fit the closure's `void *` env slot. Calling
    // `f` directly through the `(void *, ...)` code-pointer cast would be an ABI
    // mismatch (and a narrowing int-to-pointer warning), so each such `f` gets a
    // generated thunk `RET f__envthunk(void *env, P...){ return f((T)(uintptr_t)env, P...); }`
    // whose signature genuinely matches the slot. Keyed by thunk name.
    bind_thunks: std.StringHashMap(BindThunk),
    mir_module: *const mir.Module,
    source_path: ?[]const u8,
    reporter: ?*diagnostics.Reporter = null,
    // Sanitizer profile (D2.1/2.2/2.3). When set, ordinary (non-raw, non-global) scalar LOADS
    // through a struct field / array element are wrapped with the shadow hook via a comma
    // expression, so a UAF/OOB reached through a field or element is caught — matching the LLVM
    // backend. Global loads/stores are already instrumented inside the `mc_race_*` macro. All
    // false by default (no hook emitted).
    ksan: bool = false,
    msan: bool = false,
    csan: bool = false,
    // `--stub-asm` (test-only): replace each inline-asm block with a host-neutral stub so an
    // arch module's portable logic can be compiled/run host-natively. Default false → asm is
    // emitted verbatim (kernel/bare-metal builds unchanged).
    stub_asm: bool = false,
    current_function: ?[]const u8 = null,
    temp_index: usize,
    indent: usize,
    fn init(allocator: std.mem.Allocator, out: *std.ArrayList(u8), mir_module: *const mir.Module, source_path: ?[]const u8, reporter: ?*diagnostics.Reporter) CEmitter {
        return .{
            .allocator = allocator,
            .out = out,
            .scratch = std.heap.ArenaAllocator.init(allocator),
            .emitted_string_backings = std.AutoHashMap(mir.StringBackingId, void).init(allocator),
            .type_aliases = std.StringHashMap(ast_bridge.TypeExpr).init(allocator),
            .functions = std.StringHashMap(FnInfo).init(allocator),
            .backend_names = std.StringHashMap([]const u8).init(allocator),
            .structs = std.StringHashMap(ast_bridge.StructDecl).init(allocator),
            .mmio_structs = std.StringHashMap(MmioStruct).init(allocator),
            .packed_bits = std.StringHashMap(PackedBitsInfo).init(allocator),
            .overlay_unions = std.StringHashMap(OverlayUnionInfo).init(allocator),
            .tagged_unions = std.StringHashMap(ast_bridge.UnionDecl).init(allocator),
            .enums = std.StringHashMap(ast_bridge.EnumDecl).init(allocator),
            .array_types = std.StringHashMap(ArrayInfo).init(allocator),
            .slice_types = std.StringHashMap(SliceInfo).init(allocator),
            .result_types = std.StringHashMap(ResultInfo).init(allocator),
            .opt_types = std.StringHashMap(lower_c_model.OptInfo).init(allocator),
            .fn_ptr_types = std.StringHashMap(ast_bridge.TypeExpr).init(allocator),
            .closure_types = std.StringHashMap(ast_bridge.TypeExpr).init(allocator),
            .signature_type_defs = std.AutoHashMap(mir.SignatureTypeId, void).init(allocator),
            .bind_thunks = std.StringHashMap(BindThunk).init(allocator),
            .mir_module = mir_module,
            .source_path = source_path,
            .reporter = reporter,
            .temp_index = 0,
            .indent = 0,
        };
    }

    pub fn deinit(self: *CEmitter) void {
        self.deinitFunctionCollections();
        self.deinitTypeCollections();
        self.deinitDeclCollections();
        self.signature_type_defs.deinit();
        self.scratch.deinit();
    }

    fn deinitFunctionCollections(self: *CEmitter) void {
        self.fn_ptr_types.deinit();
        self.closure_types.deinit();
        self.bind_thunks.deinit();
        self.functions.deinit();
        self.backend_names.deinit();
    }

    fn deinitTypeCollections(self: *CEmitter) void {
        self.opt_types.deinit();
        self.result_types.deinit();
        self.slice_types.deinit();
        self.array_types.deinit();
        self.enums.deinit();
        var packed_bits = self.packed_bits.valueIterator();
        while (packed_bits.next()) |bits| bits.fields.deinit();
        self.packed_bits.deinit();
        var overlay_unions = self.overlay_unions.valueIterator();
        while (overlay_unions.next()) |overlay_union| overlay_union.fields.deinit();
        self.overlay_unions.deinit();
        self.tagged_unions.deinit();
        var mmio_structs = self.mmio_structs.valueIterator();
        while (mmio_structs.next()) |mmio_struct| mmio_struct.fields.deinit();
        self.mmio_structs.deinit();
        self.structs.deinit();
        self.type_aliases.deinit();
    }

    fn deinitDeclCollections(self: *CEmitter) void {
        self.emitted_string_backings.deinit();
    }

    fn collectModule(self: *CEmitter) anyerror!void {
        try self.collectTypeAliasFacts();
        try self.collectEnumFacts();
        try self.collectPackedBitsFacts();
        try self.collectOverlayUnionFacts();
        try self.collectTaggedUnionFacts();
        try self.collectStructFacts();
        try self.collectCallableEmissionFacts();
        try self.collectCheckedPlannedGlobals();
        try self.collectBindThunks();
    }

    /// Materialize legacy helper input from the single module-owned alias
    /// fact table. No declaration artifact carries a type-alias AST payload.
    fn collectTypeAliasFacts(self: *CEmitter) !void {
        for (self.mir_module.type_aliases) |fact| {
            const identity = self.typeAliasIdentity(fact) orelse return error.UnsupportedCEmission;
            const target = try signature_type_materializer.typeExpr(
                self.scratch.allocator(),
                self.mir_module.signature_types,
                fact.target_type_id,
                .{ .offset = 0, .len = 0, .line = 0, .column = 0 },
            );
            if (self.type_aliases.contains(identity.spelling)) return error.UnsupportedCEmission;
            try self.type_aliases.put(identity.spelling, target);
        }
    }

    /// Enum AST views are derived solely from checked module facts for the
    /// remaining legacy expression helpers. No declaration artifact carries
    /// an enum AST ingress.
    fn collectEnumFacts(self: *CEmitter) !void {
        for (self.mir_module.enums) |fact| {
            const enum_decl = try signature_type_materializer.enumDecl(
                self.scratch.allocator(),
                self.mir_module.signature_types,
                self.mir_module.symbol_identities,
                fact,
            );
            if (self.enums.contains(enum_decl.name.text)) return error.UnsupportedCEmission;
            try self.enums.put(enum_decl.name.text, enum_decl);
        }
    }

    /// Packed-bits rendering views are derived from module-owned checked
    /// facts. No declaration artifact carries a packed-bits AST payload.
    fn collectPackedBitsFacts(self: *CEmitter) !void {
        for (self.mir_module.packed_bits) |fact| {
            const packed_bits = try signature_type_materializer.packedBitsDecl(
                self.scratch.allocator(),
                self.mir_module.signature_types,
                self.mir_module.symbol_identities,
                fact,
            );
            try self.collectPackedBits(packed_bits);
        }
    }

    /// Overlay storage and field layouts are admitted module facts. The
    /// materialized types below are rendering inputs only; no backend layout
    /// calculation is permitted on this path.
    fn collectOverlayUnionFacts(self: *CEmitter) !void {
        for (self.mir_module.overlay_unions) |fact| {
            const overlay_union = try signature_type_materializer.overlayUnionDecl(
                self.scratch.allocator(),
                self.mir_module.signature_types,
                self.mir_module.symbol_identities,
                fact,
            );
            try self.collectOverlayUnionFact(overlay_union, fact);
        }
    }

    /// Tagged-union cases and layout are admitted module facts. The AST value
    /// below is a render-only bridge for legacy expression helpers.
    fn collectTaggedUnionFacts(self: *CEmitter) !void {
        for (self.mir_module.tagged_unions) |fact| {
            const tagged_union = try signature_type_materializer.taggedUnionDecl(
                self.scratch.allocator(),
                self.mir_module.signature_types,
                self.mir_module.symbol_identities,
                fact,
            );
            try self.collectTaggedUnion(tagged_union);
        }
    }

    /// Ordinary aggregates are admitted as syntax-free module facts.  The
    /// materialized declaration is a rendering/eval bridge only.
    fn collectStructFacts(self: *CEmitter) !void {
        for (self.mir_module.structs) |fact| {
            const struct_decl = try signature_type_materializer.structDecl(
                self.scratch.allocator(),
                self.mir_module.signature_types,
                self.mir_module.symbol_identities,
                fact,
            );
            if (!isMmioStructAbi(struct_decl)) try self.structs.put(struct_decl.name.text, struct_decl);
        }
        for (self.mir_module.structs) |fact| {
            const struct_decl = try signature_type_materializer.structDecl(
                self.scratch.allocator(),
                self.mir_module.signature_types,
                self.mir_module.symbol_identities,
                fact,
            );
            try self.collectStructFact(struct_decl);
        }
    }

    /// Seed backend lookup/comptime state from checked global facts. Every
    /// global, including an extern declaration, is represented here without
    /// retaining an AST initializer or declaration payload.
    fn collectCheckedPlannedGlobals(self: *CEmitter) !void {
        for (self.mir_module.checked_globals) |global| {
            const ty = try self.signatureTypeExpr(global.signature_type_id, spanFromSourcePoint(global.declaration_source));
            try self.collectTypeArtifacts(ty);
            const fact = self.mir_module.checkedGlobalInitializer(global) orelse continue;
            _ = fact;
        }
    }

    fn collectStructFact(self: *CEmitter, struct_decl: ast_bridge.StructDecl) !void {
        if (isMmioStructAbi(struct_decl)) {
            try self.collectMmioStruct(struct_decl);
            return;
        }
        for (struct_decl.fields) |field| try self.collectTypeArtifacts(field.ty);
    }

    fn collectCallableEmissionFacts(self: *CEmitter) !void {
        for (self.mir_module.callable_emission_facts) |fact| {
            const checked = self.checkedCallableFact(fact.def_id) orelse return error.UnsupportedCEmission;
            const name = self.callableSymbol(fact) orelse return error.UnsupportedCEmission;
            if (fact.params.len != checked.param_count or fact.params.len != checked.param_types.len or
                fact.params.len != checked.signature_param_type_ids.len)
                return error.UnsupportedCEmission;
            for (checked.signature_param_type_ids) |type_id| if (!self.mir_module.signature_types.contains(type_id)) return error.UnsupportedCEmission;
            const fn_mir = self.mirFunctionByDefId(fact.def_id) orelse return error.UnsupportedCEmission;
            if (!std.mem.eql(u8, name, fn_mir.name) or !mir.ValueType.eql(checked.return_ty, fn_mir.return_ty) or
                !checked.signature_return_type_id.eql(fn_mir.signature_return_type_id) or checked.kind == .global_initializer)
                return error.UnsupportedCEmission;
            const params = try self.scratch.allocator().alloc(lower_c_model.FnParamInfo, fact.params.len);
            for (params, checked.param_types, checked.signature_param_type_ids) |*param, value_ty, type_id| {
                param.* = .{ .value_ty = value_ty, .type_id = type_id };
            }
            try self.functions.put(name, .{
                .params = params,
                .return_ty = checked.return_ty,
                .return_type_id = checked.signature_return_type_id,
                .is_extern = checked.kind == .extern_function,
                .is_variadic = checked.is_variadic,
                .error_from = fact.error_from,
            });
            if (checked.kind != .extern_function) if (fact.backend_name) |backend_name| try self.backend_names.put(name, backend_name);
            try self.collectCallableEmissionFactSliceTypes(name, fn_mir);
        }
    }

    pub fn collectBindThunks(self: *CEmitter) anyerror!void {
        // MIR owns the `bind(env, f)` call inventory. The C backend only uses it
        // to predeclare scalar-env thunks before function bodies are emitted.
        for (self.mir_module.functions) |fn_mir| {
            if (fn_mir.is_extern) continue;
            for (fn_mir.bind_thunk_facts) |fact| try self.collectBindThunkFact(fn_mir, fact);
            for (fn_mir.executable_body.expressions) |expression| switch (expression.operation) {
                .closure_bind => |bind| if (bind.capture_encoding == .integer) {
                    const target = executableSymbolSpelling(&fn_mir.executable_body, bind.target) orelse
                        return error.UnsupportedCEmission;
                    const code = executableSymbolSpelling(&fn_mir.executable_body, bind.code) orelse
                        return error.UnsupportedCEmission;
                    const info = self.functions.get(target) orelse return error.UnsupportedCEmission;
                    if (info.params.len == 0 or info.is_extern) return error.UnsupportedCEmission;
                    if (!self.bind_thunks.contains(code)) try self.bind_thunks.put(code, .{ .fname = target, .info = info });
                },
                else => {},
            };
        }
    }

    fn executableSymbolSpelling(body: *const mir.ExecutableBody, id: mir.SymbolId) ?[]const u8 {
        if (!id.isValid() or id.index() >= body.symbols.len) return null;
        const identity = body.symbols[id.index()];
        return if (identity.id.eql(id) and identity.kind == .function) identity.spelling else null;
    }

    fn emitModule(self: *CEmitter) anyerror!void {
        defer self.deinit();
        try self.collectModule();
        try self.emitTypePrelude();
        try self.emitFunctionDeclarations();
        try self.emitGeneratedDispatchArtifacts();
        try self.emitGlobalDefinitions();
        try self.emitFunctionDefinitions();
    }

    pub fn emitTypePrelude(self: *CEmitter) anyerror!void {
        try self.emitEnums();
        try self.emitPackedBitsTypes();
        try self.emitOverlayUnionTypes();
        try self.emitAggregateForwardDeclarations();
        // Slices lower to a struct with a pointer field, so the forward
        // declarations above suffice; emit them before the by-value aggregates
        // (a struct may embed a slice by value).
        try self.emitSliceTypes();
        // Function-pointer typedefs depend only on already-declared scalar/struct
        // types, and structs/params may reference them by name.
        try self.emitFnPtrTypes();
        try self.emitClosureTypes();
        try self.emitMmioStructTypes();
        // Arrays, structs, Result types, and tagged unions can embed one another
        // by value (`[N]S`, `struct { [N]S }`, `Result<S, E>`), so emit them in
        // dependency order rather than a fixed category order.
        // Value optionals `?T` join the dependency-ordered aggregate emission (a `?T`
        // typedef embeds its payload by value, and a struct/Result may embed a `?T`).
        try self.emitOrderedAggregates();
        try self.emitSignatureTypeDefinitions();
    }

    fn emitMmioStructTypes(self: *CEmitter) !void {
        for (self.mir_module.structs) |fact| {
            if (!fact.is_mmio) continue;
            const struct_decl = try signature_type_materializer.structDecl(
                self.scratch.allocator(),
                self.mir_module.signature_types,
                self.mir_module.symbol_identities,
                fact,
            );
            if (self.mmio_structs.contains(struct_decl.name.text)) try lower_c_mmio.emitStruct(self.mmioStructEmitContext(), struct_decl);
        }
        for (self.mir_module.checked_globals) |global| {
            if (self.mir_module.checkedGlobalInitializer(global) != null)
                try self.emitSignatureTypeDefinition(global.signature_type_id);
        }
    }

    /// Materialize aggregate callable-signature types without looking at an
    /// AST TypeExpr.  The legacy body registries remain for body lowering;
    /// signature-only declarations are owned by this one recursive walk.
    fn emitSignatureTypeDefinitions(self: *CEmitter) !void {
        for (self.mir_module.callable_emission_facts) |fact| {
            const checked = self.checkedCallableFact(fact.def_id) orelse return error.UnsupportedCEmission;
            try self.emitSignatureTypeDefinition(checked.signature_return_type_id);
            for (checked.signature_param_type_ids) |type_id| try self.emitSignatureTypeDefinition(type_id);
        }
        for (self.mir_module.checked_globals) |global| try self.emitSignatureTypeDefinition(global.signature_type_id);
        // Body-local declaration shapes arrive as syntax-free IDs.  Emit
        // their required aggregate typedefs from the same module table rather
        // than retaining AST TypeExpr payloads on MIR functions.
        for (self.mir_module.functions) |function| {
            for (function.body_signature_type_ids) |id| try self.emitSignatureTypeDefinition(id);
            for (function.target_type_facts) |fact| try self.emitSignatureTypeDefinition(fact.target_type_id);
        }
    }

    fn emitSignatureTypeDefinition(self: *CEmitter, id: mir.SignatureTypeId) !void {
        if (self.signature_type_defs.contains(id)) return;
        const shape = signature_type_mechanics.shape(self.mir_module.signature_types, id) catch return error.UnsupportedCEmission;
        switch (shape) {
            .qualified => |node| try self.emitSignatureTypeDefinition(node.child),
            .pointer => |node| try self.emitSignatureTypeDefinition(node.child),
            .raw_many_pointer => |node| try self.emitSignatureTypeDefinition(node.child),
            .slice => |node| try self.emitSignatureTypeDefinition(node.child),
            .array => |node| try self.emitSignatureTypeDefinition(node.child),
            .nullable => |child| try self.emitSignatureTypeDefinition(child),
            .generic => |node| for (node.args) |arg| try self.emitSignatureTypeDefinition(arg),
            .fn_pointer => |node| {
                try self.emitSignatureTypeDefinition(node.ret);
                for (node.params) |param| try self.emitSignatureTypeDefinition(param);
            },
            .closure_type => |node| {
                try self.emitSignatureTypeDefinition(node.ret);
                for (node.params) |param| try self.emitSignatureTypeDefinition(param);
            },
            .name, .enum_literal, .member => {},
            .dyn_trait => return error.UnsupportedCEmission,
        }
        try self.signature_type_defs.put(id, {});

        switch (shape) {
            .slice => |node| {
                const name = try self.cSignatureType(id);
                if (self.slice_types.contains(name)) return;
                const child = try self.cSignatureType(node.child);
                const ptr = if (node.mutability == .mut) try std.fmt.allocPrint(self.scratch.allocator(), "{s} *", .{child}) else try std.fmt.allocPrint(self.scratch.allocator(), "{s} const *", .{child});
                try self.out.print(self.allocator, "typedef struct {s} {{\n    {s} ptr;\n    uintptr_t len;\n}} {s};\n\n", .{ name, ptr, name });
            },
            .array => |node| {
                const name = try self.cSignatureType(id);
                if (self.array_types.contains(name)) return;
                const length = node.length orelse return error.UnsupportedCEmission;
                try self.out.print(self.allocator, "typedef struct {s} {{\n    {s} elems[{d}];\n}} {s};\n\n", .{ name, try self.cSignatureType(node.child), length, name });
            },
            .nullable => |child| if (!self.signatureTypeIsPointerLike(child)) {
                const name = try self.cSignatureType(id);
                if (self.opt_types.contains(name)) return;
                try self.out.print(self.allocator, "typedef struct {s} {{\n    bool present;\n    {s} value;\n}} {s};\n\n", .{ name, try self.cSignatureType(child), name });
            },
            .generic => |node| if (std.mem.eql(u8, node.base, "Result") and node.args.len == 2) {
                const name = try self.cSignatureType(id);
                if (self.result_types.contains(name)) return;
                const ok = if (try signature_type_mechanics.isVoid(self.mir_module.signature_types, node.args[0])) "unsigned char" else try self.cSignatureType(node.args[0]);
                const err = if (try signature_type_mechanics.isVoid(self.mir_module.signature_types, node.args[1])) "unsigned char" else try self.cSignatureType(node.args[1]);
                try self.out.print(self.allocator, "typedef struct {s} {{\n    bool is_ok;\n    union {{\n        {s} ok;\n        {s} err;\n    }} payload;\n}} {s};\n\n", .{ name, ok, err, name });
            },
            .fn_pointer => |node| {
                const name = try self.cSignatureType(id);
                if (self.fn_ptr_types.contains(name)) return;
                try self.out.print(self.allocator, "typedef {s} (*{s})(", .{ try self.cSignatureType(node.ret), name });
                if (node.params.len == 0) {
                    try self.out.appendSlice(self.allocator, "void");
                } else for (node.params, 0..) |param, index| {
                    if (index != 0) try self.out.appendSlice(self.allocator, ", ");
                    try self.out.appendSlice(self.allocator, try self.cSignatureType(param));
                }
                try self.out.appendSlice(self.allocator, ");\n\n");
            },
            .closure_type => |node| {
                const name = try self.cSignatureType(id);
                if (self.closure_types.contains(name)) return;
                try self.out.print(self.allocator, "typedef struct {{ {s} (*code)(void *", .{try self.cSignatureType(node.ret)});
                for (node.params) |param| try self.out.print(self.allocator, ", {s}", .{try self.cSignatureType(param)});
                try self.out.print(self.allocator, "); void *env; }} {s};\n\n", .{name});
            },
            else => {},
        }
    }

    pub fn emitFunctionDeclarations(self: *CEmitter) anyerror!void {
        // Forward-declare every defined function up front so a call to a function
        // declared later in the (possibly import-merged) source resolves — MC
        // resolves calls module-wide, independent of declaration order.
        for (self.mir_module.callable_emission_facts) |fact| {
            const checked = self.checkedCallableFact(fact.def_id) orelse return error.UnsupportedCEmission;
            if (checked.kind == .extern_function) {
                // Extern prototypes must precede any function body that calls them;
                // an imported `extern fn` can be merged after its caller.
                try self.emitExternFunction(fact);
            } else if (checked.kind == .function and checked.body_id.isValid()) {
                try self.emitFunctionForwardDecl(fact);
            } else return error.UnsupportedCEmission;
        }
    }

    pub fn emitGeneratedDispatchArtifacts(self: *CEmitter) !void {
        // Env-widening thunks for scalar-env closures: emit after the function
        // forward declarations (the thunks call those functions) and before any
        // body that might `bind` through one.
        try lower_c_dispatch.emitBindThunks(self.bindThunkContext(), &self.bind_thunks);
        // Rodata vtable instances: one `static const VT_Trait __vt_Type_Trait = {…}`
        // per `impl Trait for Type` of an object-safe trait. Emitted after the function
        // forward declarations the initializer references.
    }

    pub fn emitGlobalDefinitions(self: *CEmitter) anyerror!void {
        // Emit every global before any function body. MC resolves names
        // module-wide regardless of declaration order, and import-merged sources
        // can place a function ahead of a global it reads (e.g. a `const` defined
        // in an imported module). Globals are simple `static` definitions, so
        // emitting them first satisfies C's declare-before-use without needing
        // forward declarations.
        try self.emitCheckedStringBackings();
        for (self.mir_module.checked_globals) |global| {
            const fact = self.mir_module.checkedGlobalInitializer(global) orelse continue;
            switch (fact.plan) {
                .scalar => try self.emitCheckedScalarGlobal(global, fact),
                .zero => try self.emitCheckedZeroGlobal(global),
                .atomic_init => |plan| try self.emitCheckedAtomicInitGlobal(global, plan),
                .aggregate => |plan| try self.emitCheckedAggregateGlobal(global, plan),
                .enum_case => |plan| try self.emitCheckedEnumGlobal(global, plan),
                .nullable_null => try self.emitCheckedNullableNullGlobal(global),
                .string_bytes => |plan| try self.emitCheckedStringBytesGlobal(global, plan),
                .global_address => |plan| try self.emitCheckedGlobalAddressGlobal(global, plan),
                .function_symbol => |plan| try self.emitCheckedFunctionSymbolGlobal(global, plan),
            }
        }
        for (self.mir_module.checked_globals) |global| {
            if (!global.is_extern) continue;
            try self.emitCheckedExternGlobal(global);
        }
    }

    pub fn emitFunctionDefinitions(self: *CEmitter) anyerror!void {
        // Function-definition admission is driven exclusively by verified MIR.
        for (self.mir_module.functions) |fn_mir| {
            if (fn_mir.is_extern) continue;
            // Global initializer bodies are compiler-internal checked MIR, not
            // callable declarations. They deliberately have no callable emission fact
            // and are identified by the absence of a declaration DefId, rather
            // than by positional coupling to the checked-callable table.
            if (!fn_mir.typed_def_id.isValid()) continue;
            // A verified executable body without its declaration facts is not
            // a declaration we can safely render.  In particular, do not
            // silently omit it: the old AST body fallback made that kind of
            // omission easy to hide.  Codegen has one body authority now, so
            // an incomplete ingress must fail closed.
            const fact = self.mir_module.callableEmissionFact(fn_mir.typed_def_id) orelse return error.UnsupportedCEmission;
            const checked = self.checkedCallableFact(fact.def_id) orelse return error.UnsupportedCEmission;
            const name = self.callableSymbol(fact) orelse return error.UnsupportedCEmission;
            if (!std.mem.eql(u8, name, fn_mir.name) or checked.kind != .function) return error.UnsupportedCEmission;
            const render_attrs = fact.render_attrs;
            const previous_source_path = self.source_path;
            self.source_path = self.sourcePathForSpan(spanFromMirSourcePoint(fact.declaration_source));
            defer self.source_path = previous_source_path;
            if (try self.emitVerifiedMirFunction(fact, fn_mir, render_attrs)) {
                continue;
            } else if (mir_executable_body.explicitUnsupported(&fn_mir)) |unsupported| {
                self.reportUnsupported(spanFromMirSourcePoint(unsupported.source), unsupported.construct());
                return error.UnsupportedCEmission;
            } else {
                return error.UnsupportedCEmission;
            }
        }
    }

    fn checkedCallableFact(self: *const CEmitter, def_id: mir.DefId) ?mir.CheckedCallableFact {
        if (!def_id.isValid()) return null;
        var found: ?mir.CheckedCallableFact = null;
        for (self.mir_module.checked_callables) |fact| {
            if (!fact.def_id.eql(def_id)) continue;
            if (found != null) return null;
            found = fact;
        }
        return found;
    }

    fn callableSymbol(self: *const CEmitter, fact: mir.CallableEmissionFact) ?[]const u8 {
        if (!fact.symbol_id.isValid() or fact.symbol_id.index() >= self.mir_module.symbol_identities.len) return null;
        const identity = self.mir_module.symbol_identities[fact.symbol_id.index()];
        return if (identity.id.eql(fact.symbol_id) and identity.kind == .function) identity.spelling else null;
    }

    fn emitCheckedExternGlobal(self: *CEmitter, global: mir.CheckedGlobalFact) !void {
        const name = self.checkedGlobalSymbol(global) orelse return error.UnsupportedCEmission;
        const rendered_type = try self.cSignatureType(global.signature_type_id);
        try self.writeLineDirective(spanFromSourcePoint(global.declaration_source));
        try self.out.print(self.allocator, "#undef {s}\nextern {s} {s};\n\n", .{ name, rendered_type, name });
    }

    fn emitCheckedScalarGlobal(self: *CEmitter, global: mir.CheckedGlobalFact, fact: mir.GlobalInitializerFact) !void {
        const name = self.checkedGlobalSymbol(global) orelse return error.UnsupportedCEmission;
        const rendered_type = try mir_executable_c.renderType(self.scratch.allocator(), &mir.ExecutableBody{}, global.ty);
        const value = (try self.constGlobalCValue(fact.initializer_body_id, global.ty)) orelse return error.UnsupportedCEmission;
        try self.writeLineDirective(spanFromSourcePoint(global.declaration_source));
        try self.out.print(self.allocator, "#undef {s}\n", .{name});
        try self.out.appendSlice(self.allocator, if (global.exported) "MC_UNUSED " else "static MC_UNUSED ");
        try self.out.print(self.allocator, "{s} {s} = {s};\n\n", .{ rendered_type, name, value });
    }

