    fn cEnumCaseInitializer(self: *CEmitter, symbol_id: mir.SymbolId, value: mir.EnumCaseFact) ![]const u8 {
        if (!symbol_id.isValid() or symbol_id.index() >= self.mir_module.symbol_identities.len) return error.UnsupportedCEmission;
        const identity = self.mir_module.symbol_identities[symbol_id.index()];
        if (!identity.id.eql(symbol_id) or identity.kind != .type_) return error.UnsupportedCEmission;
        return std.fmt.allocPrint(self.scratch.allocator(), "{s}_{s}", .{ identity.spelling, value.spelling });
    }

    fn cAggregateGlobalInitializer(self: *CEmitter, plan: mir.AggregateInitializerPlan, id: mir.SignatureTypeId) ![]const u8 {
        return switch (plan) {
            .scalar => |value| self.cScalarGlobalValue(value),
            .function_symbol => |value| self.checkedFunctionSymbolId(value.target_symbol_id) orelse error.UnsupportedCEmission,
            .array => |items| blk: {
                const shape = signature_type_mechanics.shape(self.mir_module.signature_types, id) catch return error.UnsupportedCEmission;
                const array = switch (shape) {
                    .array => |value| value,
                    else => return error.UnsupportedCEmission,
                };
                const length = array.length orelse return error.UnsupportedCEmission;
                if (items.len != length) return error.UnsupportedCEmission;
                var text: std.ArrayList(u8) = .empty;
                try text.appendSlice(self.scratch.allocator(), "{ ");
                for (items, 0..) |item, index| {
                    if (index != 0) try text.appendSlice(self.scratch.allocator(), ", ");
                    try text.appendSlice(self.scratch.allocator(), try self.cAggregateGlobalInitializer(item, array.child));
                }
                try text.appendSlice(self.scratch.allocator(), " }");
                break :blk try text.toOwnedSlice(self.scratch.allocator());
            },
            .struct_ => |struct_plan| blk: {
                const struct_fact = self.structFact(struct_plan.struct_symbol_id) orelse return error.UnsupportedCEmission;
                if (struct_plan.fields.len != struct_fact.fields.len) return error.UnsupportedCEmission;
                var text: std.ArrayList(u8) = .empty;
                try text.appendSlice(self.scratch.allocator(), "{ ");
                for (struct_plan.fields, 0..) |field, index| {
                    if (field.field_index != index or index >= struct_fact.fields.len) return error.UnsupportedCEmission;
                    const struct_field = struct_fact.fields[index];
                    if (index != 0) try text.appendSlice(self.scratch.allocator(), ", ");
                    try text.print(self.scratch.allocator(), ".{s} = {s}", .{ struct_field.spelling, try self.cAggregateGlobalInitializer(field.value, struct_field.type_id) });
                }
                try text.appendSlice(self.scratch.allocator(), " }");
                break :blk try text.toOwnedSlice(self.scratch.allocator());
            },
            .zero => "{ 0 }",
            .enum_case => |value| blk: {
                const enum_fact = self.enumFact(value.enum_symbol_id) orelse return error.UnsupportedCEmission;
                if (!enum_fact.repr_type_id.eql(value.repr_type_id) or value.case_index >= enum_fact.cases.len) return error.UnsupportedCEmission;
                break :blk try self.cEnumCaseInitializer(value.enum_symbol_id, enum_fact.cases[value.case_index]);
            },
            .string_bytes => |value| blk: {
                const ty = try self.cSignatureType(id);
                break :blk try std.fmt.allocPrint(self.scratch.allocator(), "(({s}){s})", .{ ty, try self.cStringBackingName(value.backing_id) });
            },
            .global_address => |value| blk: {
                const target = self.checkedGlobalSymbolId(value.target_symbol_id) orelse return error.UnsupportedCEmission;
                break :blk try std.fmt.allocPrint(self.scratch.allocator(), "&{s}", .{target});
            },
        };
    }

