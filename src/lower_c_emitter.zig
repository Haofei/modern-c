    fn emitFunctionSignature(self: *CEmitter, fact: mir.CallableEmissionFact, fn_mir: mir.Function, is_static: bool, with_asm_label: bool) !void {
        const checked = self.checkedCallableFact(fact.def_id) orelse return error.UnsupportedCEmission;
        const name = self.callableSymbol(fact) orelse return error.UnsupportedCEmission;
        if (!std.mem.eql(u8, name, fn_mir.name) or !mir.ValueType.eql(checked.return_ty, fn_mir.return_ty) or
            fact.params.len != fn_mir.param_types.len or !self.mir_module.signature_types.contains(checked.signature_return_type_id)) return error.UnsupportedCEmission;
        const ret = try self.cSignatureType(checked.signature_return_type_id);
        const param_types = try self.scratch.allocator().alloc([]const u8, fact.params.len);
        for (fn_mir.param_types, checked.param_types, checked.signature_param_type_ids, 0..) |param_ty, checked_param_ty, type_id, index| {
            if (!mir.ValueType.eql(param_ty, checked_param_ty) or !self.mir_module.signature_types.contains(type_id)) return error.UnsupportedCEmission;
            param_types[index] = try self.cSignatureType(type_id);
        }
        try lower_c_defs.emitFunctionSignature(self.defsContext(), name, fact.params, checked.is_variadic, ret, param_types, is_static, with_asm_label);
    }

    /// Render a callable signature type from the module-owned syntax-free
    /// table.  This intentionally does not recreate an AST TypeExpr.
    fn cSignatureType(self: *CEmitter, id: mir.SignatureTypeId) ![]const u8 {
        const shape = signature_type_mechanics.shape(self.mir_module.signature_types, id) catch return error.UnsupportedCEmission;
        return switch (shape) {
            // Alias targets are module-owned `TypeAliasFact` rows, not
            // callable or declaration-artifact payloads.
            .name => |name| if (self.type_aliases.get(name)) |target|
                try self.cTypeFor(target, .typedef_name)
            else
                primitiveCTypeName(name) orelse try self.cIdent(name),
            .enum_literal => |name| try self.cIdent(name),
            .qualified => |node| try self.cSignatureType(node.child),
            .pointer => |node| blk: {
                const child = try self.cSignatureType(node.child);
                break :blk std.fmt.allocPrint(self.scratch.allocator(), "{s}{s} *", .{ child, if (node.mutability == .@"const") " const" else "" });
            },
            .raw_many_pointer => |node| blk: {
                const child = try self.cSignatureType(node.child);
                break :blk std.fmt.allocPrint(self.scratch.allocator(), "{s}{s} *", .{ child, if (node.mutability == .@"const") " const" else "" });
            },
            .slice => |node| std.fmt.allocPrint(self.scratch.allocator(), "mc_slice_{s}_{s}", .{ if (node.mutability == .mut) "mut" else "const", try self.cSignatureSuffix(node.child) }),
            .array => |node| std.fmt.allocPrint(self.scratch.allocator(), "mc_array_{s}_{d}", .{ try self.cSignatureSuffix(node.child), node.length orelse return error.UnsupportedCEmission }),
            .nullable => |child| if (self.signatureTypeIsPointerLike(child))
                self.cSignatureType(child)
            else
                std.fmt.allocPrint(self.scratch.allocator(), "mc_opt_{s}", .{try self.cSignatureSuffix(child)}),
            .generic => |node| self.cSignatureGenericType(node.base, node.args),
            .fn_pointer => |node| self.cSignatureCallableType("mc_fnptr", node.ret, node.params),
            .closure_type => |node| self.cSignatureCallableType("mc_closure", node.ret, node.params),
            .member => error.UnsupportedCEmission,
            .dyn_trait => error.UnsupportedCEmission,
        };
    }

    /// Shared one-way bridge for remaining legacy initializer/body mechanics.
    fn signatureTypeExpr(self: *CEmitter, id: mir.SignatureTypeId, span: diagnostics.Span) anyerror!TransitionalTypeExpr {
        return signature_type_materializer.typeExpr(self.scratch.allocator(), self.mir_module.signature_types, id, span) catch |err| switch (err) {
            error.OutOfMemory => return error.OutOfMemory,
            else => return error.UnsupportedCEmission,
