    fn typeAliasIdentity(self: *const CEmitter, fact: mir.TypeAliasFact) ?mir.SymbolIdentity {
        if (!fact.symbol_id.isValid() or fact.symbol_id.index() >= self.mir_module.symbol_identities.len) return null;
        const identity = self.mir_module.symbol_identities[fact.symbol_id.index()];
        return if (identity.id.eql(fact.symbol_id) and identity.kind == .type_) identity else null;
    }

    fn globalInitializerMir(self: *const CEmitter, body_id: mir.BodyId) ?mir.Function {
        if (!body_id.isValid()) return null;
        for (self.mir_module.functions, 0..) |function, index| {
            if (index >= self.mir_module.checked_callables.len) continue;
            const checked = self.mir_module.checked_callables[index];
            if (checked.kind == .global_initializer and checked.body_id.eql(body_id)) return function;
        }
        return null;
    }

    fn sourcePathForSpan(self: *CEmitter, span: diagnostics.Span) ?[]const u8 {
        if (span.file_id != diagnostics.invalid_file_id) {
            if (self.reporter) |reporter| if (reporter.pathForFileId(span.file_id)) |path| {
                const artifact_root = self.source_path orelse return path;
                if (std.mem.eql(u8, path, reporter.path)) return artifact_root;

                // The reporter intentionally retains real per-file paths for
                // diagnostics. Artifact paths may be remapped/redacted. Apply
                // the root file's already-decided artifact mapping to sibling
                // module files instead of leaking the reporter path through
                // canonical executable-MIR #line directives.
                const raw_dir = std.fs.path.dirname(reporter.path) orelse return path;
                const artifact_dir = std.fs.path.dirname(artifact_root) orelse return path;
                if (path.len > raw_dir.len and std.mem.startsWith(u8, path, raw_dir) and
                    std.fs.path.isSep(path[raw_dir.len]))
                {
                    return std.fmt.allocPrint(self.scratch.allocator(), "{s}{s}", .{ artifact_dir, path[raw_dir.len..] }) catch path;
                }
                return path;
            };
        }
        return self.source_path;
    }

    // Scalar const globals are rendered from a verified MIR fact. Aggregates
    // retain the transitional AST route until they receive their own
    // syntax-free const-value representation.
    fn constGlobalCValue(self: *CEmitter, body_id: mir.BodyId, value_ty: mir.ValueType) !?[]const u8 {
        const fact = self.mir_module.globalInitializerFact(body_id) orelse {
            if (mir.valueTypeRequiresScalarGlobalInitializerFact(value_ty) and body_id.isValid())
                return error.UnsupportedCEmission;
            return null;
        };
        if (!mir.ValueType.eql(fact.value_ty, value_ty) or !fact.scalarValue().isCompatibleWith(fact.value_ty)) return error.UnsupportedCEmission;
        return @as(?[]const u8, try self.cScalarGlobalValue(fact.scalarValue()));
    }

    fn cScalarGlobalValue(self: *CEmitter, scalar: mir.ConstScalarValue) ![]const u8 {
        return switch (scalar) {
            // Values above the signed-64 range need an unsigned suffix, or C
            // reads the decimal literal as implicitly unsigned (a warning).
            .int => |n| blk: {
                var text: std.ArrayList(u8) = .empty;
                try appendCSignedIntValue(self.scratch.allocator(), &text, n);
                break :blk try text.toOwnedSlice(self.scratch.allocator());
            },
            .uint => |n| blk: {
                var text: std.ArrayList(u8) = .empty;
                try lower_c_const.appendCIntValue(self.scratch.allocator(), &text, n);
                break :blk try text.toOwnedSlice(self.scratch.allocator());
            },
            .boolean => |b| if (b) "1" else "0",
            .float => |f| blk: {
                var text: std.ArrayList(u8) = .empty;
                try lower_c_const.appendCFloatBits(self.scratch.allocator(), &text, f.bits, f.width, f.width == 32);
                break :blk try text.toOwnedSlice(self.scratch.allocator());
            },
        };
    }

